function changeColor(color) {

    const productCard = document.getElementById("productCard");

    if (color === "black") {
        productCard.style.backgroundColor = "#DDDDDD";
    } else if (color === "blue") {
        productCard.style.backgroundColor = "#CFE2FF";
    } else if (color === "cream") {
        productCard.style.backgroundColor = "#F5E6CC";
    }

}

